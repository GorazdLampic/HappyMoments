    function setLocale(locale) {
        if (!TRANSLATIONS[locale]) locale = 'en';
        currentLocale = locale;
        strings = TRANSLATIONS[locale];
        localStorage.setItem('happymoments_locale', locale);
        applyTranslations();
    }

    function getLocale() { return currentLocale; }

    function t(key) {
        return strings[key] || TRANSLATIONS.en[key] || key;
    }

    function detectLocale() {
        // 1. Check saved preference
        const saved = localStorage.getItem('happymoments_locale');
        if (saved && TRANSLATIONS[saved]) return saved;

        // 2. Check browser language
        const browserLang = (navigator.language || 'en').split('-')[0].toLowerCase();
        if (TRANSLATIONS[browserLang]) return browserLang;

        // 3. Check variants
        if (['sr', 'bs'].includes(browserLang)) return 'hr';
        if (browserLang === 'ms') return 'id'; // Malay → Indonesian
        if (['uk', 'be'].includes(browserLang)) return 'ru'; // Ukrainian/Belarusian → Russian

        return 'en';
    }

    function applyTranslations() {
        // Apply to all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const val = t(key);
            if (el.tagName === 'INPUT' && el.type !== 'checkbox') {
                el.placeholder = val;
            } else if (el.tagName === 'OPTION') {
                el.textContent = val;
            } else {
                el.textContent = val;
            }
        });

        // Apply to data-i18n-placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
        });
    }

    function init() {
        const locale = detectLocale();
        setLocale(locale);
    }

    return {
        setLocale,
        getLocale,
        t,
        detectLocale,
        init,
        SUPPORTED_LOCALES,
        LOCALE_NAMES,
        applyTranslations
    };
